# -----------------------------------------------------------------------------
# R/example_data.R - documentation for the genomic-selection example datasets
# -----------------------------------------------------------------------------
#
# Generate every dataset with:
#   Rscript data-raw/generate_example_data.R
#
# Compressed package datasets are placed in data/ and flat example inputs in
# inst/extdata/. A complete inventory is written to
# inst/extdata/example_manifest.csv.
#
# Flat files
# ----------
#   example_genotypes_numeric.csv  Numeric dosage input for grm_builder.R
#   example_genotypes.hmp.txt      Equivalent HapMap input
#   example_genotypes.vcf          Equivalent VCF 4.2 input
#   example_marker_weights.csv     Optional external marker weights
#   example_BLUEs_single.csv       One BLUE per genotype
#   example_BLUEs_gxe.csv          One BLUE per genotype x environment
#   example_candidate_ids.csv      Candidate population for STPGA
#   example_target_ids.csv         Target population for STPGA/fixed split
#   example_grm.csv                Ready-to-use illustrative GRM
#   example_simulation_truth.csv   Known QTL effects for validation only
#
# R-native files
# --------------
# Each documented object has an individual .rda file and can be loaded with
# data(). gs_example_all is one named list containing every object.
# -----------------------------------------------------------------------------


#' Example Genotype Matrix
#'
#' A simulated additive-dosage matrix for 120 genotypes and 240 biallelic
#' markers on three chromosomes. Four 20-marker founder-haplotype blocks are
#' simulated per chromosome. Population-specific founder frequencies create
#' moderate genomic structure across three populations while retaining shared
#' founders. One call per marker is missing when the default settings are used,
#' leaving every marker safely above the default 0.95 call-rate threshold in
#' `grm_builder.R`.
#'
#' @format A numeric matrix with 120 rows and 240 columns. Rows are genotypes
#'   `G001` through `G120`; columns are marker IDs such as `S1_0001`. Values are
#'   0, 1, 2, or `NA`, representing alternate-allele dosage.
#' @source Generated by `data-raw/generate_example_data.R` with default seed
#'   20261106.
#' @examples
#' data(gs_example_geno)
#' dim(gs_example_geno)
#' table(gs_example_geno, useNA = "ifany")
"gs_example_geno"


#' Example Marker Map
#'
#' Genomic coordinates, alleles, and simulated LD-block membership for the 240
#' columns of `gs_example_geno`.
#'
#' @format A data frame with 240 rows and six columns:
#' \describe{
#'   \item{SNP}{Unique marker identifier.}
#'   \item{CHR}{Chromosome number (1, 2, or 3).}
#'   \item{POS}{Base-pair position, increasing within chromosome.}
#'   \item{REF}{Reference allele.}
#'   \item{ALT}{Alternate allele counted by the dosage matrix.}
#'   \item{Block}{Known simulated block identifier, such as `C1B1`.}
#' }
#' @source Generated by `data-raw/generate_example_data.R`.
#' @examples
#' data(gs_example_marker_map)
#' head(gs_example_marker_map)
#' table(gs_example_marker_map$CHR, gs_example_marker_map$Block)
"gs_example_marker_map"


#' Example External Marker Weights
#'
#' Non-uniform marker weights for demonstrating the external-weight interface
#' of `grm_builder.R`. The weights are simulated independently of phenotype and
#' therefore do not introduce trait-based marker-selection leakage.
#'
#' @format A data frame with 240 rows and two columns:
#' \describe{
#'   \item{MarkerID}{Marker identifier matching `gs_example_marker_map$SNP`.}
#'   \item{Weight}{Finite positive weight sampled between 0.5 and 1.5.}
#' }
#' @source Generated by `data-raw/generate_example_data.R`.
#' @examples
#' data(gs_example_marker_weights)
#' summary(gs_example_marker_weights$Weight)
"gs_example_marker_weights"


#' Example Single-Environment BLUE Table
#'
#' One simulated stage-1 BLUE per genotype for `gblup_cv_single.R`. BLUEs are
#' inverse-variance combinations of the available environment-specific values.
#' Some `Weight` entries are deliberately missing while `SE` remains available,
#' exercising the script's documented `1 / SE^2` fallback.
#'
#' @format A data frame with 120 rows and five columns:
#' \describe{
#'   \item{GenoID}{Genotype identifier matching the GRM.}
#'   \item{NBL}{Simulated quantitative-trait BLUE.}
#'   \item{Population}{Supplied cross-validation stratum (`P1` to `P3`).}
#'   \item{SE}{Standard error of the BLUE.}
#'   \item{Weight}{BLUE precision weight; normally the inverse variance.}
#' }
#' @source Generated by `data-raw/generate_example_data.R`.
#' @examples
#' data(gs_example_blues_single)
#' head(gs_example_blues_single)
#' sum(is.na(gs_example_blues_single$Weight))
"gs_example_blues_single"


#' Example Genotype-by-Environment BLUE Table
#'
#' Simulated stage-1 BLUEs for 120 genotypes in three environments for
#' `gblup_cv_gxe.R`. The simulation contains environment mean effects and
#' moderate genotype-by-environment reranking. Some observed rows contain only
#' `SE` or only `Weight`, and six cells have no phenotype or precision value so
#' that prediction-only rows are represented. Every genotype remains observed
#' in at least two environments.
#'
#' @format A data frame with 360 rows and six columns:
#' \describe{
#'   \item{GenoID}{Genotype identifier.}
#'   \item{Env}{Environment (`E1`, `E2`, or `E3`).}
#'   \item{NBL}{Simulated stage-1 BLUE; `NA` for prediction-only cells.}
#'   \item{Population}{Stable genotype-level stratum (`P1` to `P3`).}
#'   \item{SE}{Standard error, possibly missing when `Weight` is present.}
#'   \item{Weight}{Precision weight, possibly missing when `SE` is present.}
#' }
#' @source Generated by `data-raw/generate_example_data.R`.
#' @examples
#' data(gs_example_blues_gxe)
#' with(gs_example_blues_gxe, table(Env, is.na(NBL)))
#' with(gs_example_blues_gxe, table(Population, Env))
"gs_example_blues_gxe"


#' Example STPGA Candidate IDs
#'
#' Genotypes eligible for selection by `optimize_training_population.R` in
#' targeted mode. Candidate and target IDs are disjoint and together cover the
#' complete example GRM.
