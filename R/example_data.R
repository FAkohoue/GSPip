#'
#' @format A one-column data frame with 30 rows. `GenoID` contains unique IDs.
#' @source Generated by `data-raw/generate_example_data.R`.
#' @examples
#' data(gs_example_target_ids)
#' head(gs_example_target_ids)
"gs_example_target_ids"


#' Example Genomic Relationship Matrix
#'
#' A ready-to-use additive genomic relationship matrix computed from the
#' mean-imputed example dosages using the first VanRaden formulation. A diagonal
#' ridge of 1e-6 is added for numerical positive definiteness. This object lets
#' the optimization and GBLUP scripts be explored without first running
#' `grm_builder.R`; production analyses should build and audit their own GRM.
#'
#' @format A symmetric numeric matrix with 120 rows and 120 columns. Row and
#'   column names are genotype IDs `G001` through `G120`.
#' @source Generated by `data-raw/generate_example_data.R`.
#' @examples
#' data(gs_example_grm)
#' dim(gs_example_grm)
#' range(eigen(gs_example_grm, symmetric = TRUE, only.values = TRUE)$values)
"gs_example_grm"


#' Example Simulation Truth
#'
#' Known additive and genotype-by-environment marker effects used to simulate
#' the example BLUEs. This table is supplied for validation and teaching only.
#' It must not be used to select markers before assessing prediction on the same
#' phenotypes, because that would leak the simulated outcome-generating truth.
#'
#' @format A data frame with 240 rows and six columns: `MarkerID`,
#'   `AdditiveEffect`, `GxEEffect`, `CHR`, `POS`, and `Block`. Effects are zero
#'   for markers not sampled as causal.
#' @source Generated by `data-raw/generate_example_data.R`.
#' @examples
#' data(gs_example_truth)
#' subset(gs_example_truth, AdditiveEffect != 0 | GxEEffect != 0)
"gs_example_truth"


